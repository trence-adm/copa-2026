import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import * as pdfjsLib from 'pdfjs-dist/legacy/build/pdf.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const PDF_PATH = path.join(ROOT, 'src', 'assets', 'Todas.Figurinhas.2026.Qualidade.Media.pdf');
const OUTPUT_DIR = path.join(ROOT, 'assets', 'stickers');
const CATALOG_PATH = path.join(ROOT, 'src', 'data', 'stickerImageCatalog.ts');

const STICKERS_PER_TEAM = 20;
const TEAM_CODES_IN_ALBUM_ORDER = [
  'MEX', 'CAN', 'USA', 'ARG', 'BRA', 'URU', 'COL', 'ECU', 'CHI', 'PER',
  'PAR', 'VEN', 'ENG', 'FRA', 'ESP', 'GER', 'POR', 'NED', 'ITA', 'BEL',
  'CRO', 'SUI', 'DEN', 'SWE', 'NOR', 'POL', 'SRB', 'AUT', 'TUR', 'UKR',
  'MAR', 'SEN', 'NGA', 'GHA', 'CMR', 'TUN', 'ALG', 'EGY', 'JPN', 'KOR',
  'AUS', 'IRN', 'KSA', 'QAT', 'IRQ', 'UAE', 'NZL', 'CRC',
];

pdfjsLib.GlobalWorkerOptions.workerSrc = new URL(
  '../node_modules/pdfjs-dist/legacy/build/pdf.worker.mjs',
  import.meta.url,
).href;

async function ensureDir(dirPath) {
  await fs.mkdir(dirPath, { recursive: true });
}

function buildStickerKeys() {
  const keys = [];
  for (const code of TEAM_CODES_IN_ALBUM_ORDER) {
    for (let number = 1; number <= STICKERS_PER_TEAM; number++) {
      keys.push(`${code}-${number}`);
    }
  }
  return keys;
}

function detectChannels(imageObj) {
  const pixelCount = imageObj.width * imageObj.height;
  const ratio = imageObj.data.length / pixelCount;

  if (ratio >= 4) return 4;
  if (ratio >= 3) return 3;
  if (ratio >= 1) return 1;
  return 3;
}

async function extractRawImage(imageObj, outputBaseName) {
  const channels = detectChannels(imageObj);
  const raw = {
    width: imageObj.width,
    height: imageObj.height,
    channels,
  };

  const colorFile = path.join(OUTPUT_DIR, `${outputBaseName}.webp`);
  const bwFile = path.join(OUTPUT_DIR, `${outputBaseName}-bw.webp`);

  const basePipeline = sharp(Buffer.from(imageObj.data), { raw })
    .resize({ width: 360, height: 520, fit: 'cover' });

  await basePipeline.clone().webp({ quality: 78, effort: 4 }).toFile(colorFile);
  await basePipeline.clone().grayscale().webp({ quality: 76, effort: 4 }).toFile(bwFile);
}

async function extractFromPdf() {
  const url =
    'file:///' + PDF_PATH.replace(/\\/g, '/').replace(/ /g, '%20').replace(/\+/g, '%2B');

  const doc = await pdfjsLib
    .getDocument({
      url,
      useWorkerFetch: false,
      isEvalSupported: false,
      useSystemFonts: true,
    })
    .promise;

  const extractedImageIds = [];

  for (let pageIndex = 1; pageIndex <= doc.numPages; pageIndex++) {
    const page = await doc.getPage(pageIndex);
    let op;
    try {
      op = await page.getOperatorList();
    } catch (err) {
      console.warn(`Skipping page ${pageIndex}: ${err.message}`);
      continue;
    }

    for (let i = 0; i < op.fnArray.length; i++) {
      if (op.fnArray[i] !== pdfjsLib.OPS.paintImageXObject) continue;
      const id = op.argsArray[i][0];
      if (typeof id !== 'string') continue;
      extractedImageIds.push({ page: pageIndex, id, page });
    }
  }

  const stickerKeys = buildStickerKeys();
  const mappedColorKeys = [];

  let index = 0;
  for (const item of extractedImageIds) {
    if (index >= stickerKeys.length) break;

    let imageObj;
    try {
      imageObj = item.page.objs.get(item.id);
    } catch {
      continue;
    }

    if (!imageObj || !imageObj.width || !imageObj.height || !imageObj.data) {
      continue;
    }

    // Filter out tiny artifacts/icons and keep sticker-like proportions.
    if (imageObj.width < 220 || imageObj.height < 300) {
      continue;
    }

    const key = stickerKeys[index];
    await extractRawImage(imageObj, key);
    mappedColorKeys.push(key);
    index += 1;

    if (index % 50 === 0) {
      console.log(`Extracted ${index} stickers...`);
    }
  }

  return mappedColorKeys;
}

async function writeCatalog(keys) {
  const sorted = [...keys].sort((a, b) => a.localeCompare(b));

  const colorLines = sorted.map(
    (key) => `  '${key}': require('../../assets/stickers/${key}.webp'),`,
  );
  const bwLines = sorted.map(
    (key) => `  '${key}': require('../../assets/stickers/${key}-bw.webp'),`,
  );

  const content = `export type StickerImageCatalog = Record<string, ReturnType<typeof require>>;

// Auto-generated by scripts/extract-stickers-2026.mjs
export const STICKER_IMAGE_CATALOG: StickerImageCatalog = {
${colorLines.join('\n')}
};

// Auto-generated by scripts/extract-stickers-2026.mjs
export const STICKER_BW_CATALOG: StickerImageCatalog = {
${bwLines.join('\n')}
};
`;

  await fs.writeFile(CATALOG_PATH, content, 'utf8');
}

async function main() {
  await ensureDir(OUTPUT_DIR);

  console.log(`Reading ${path.relative(ROOT, PDF_PATH)}...`);
  const extractedKeys = await extractFromPdf();

  if (extractedKeys.length === 0) {
    console.log('No sticker images were extracted from the PDF.');
    return;
  }

  await writeCatalog(extractedKeys);

  console.log(`Done. Extracted ${extractedKeys.length} sticker images.`);
  console.log(`Generated ${path.relative(ROOT, CATALOG_PATH)}.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
