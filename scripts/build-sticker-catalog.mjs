import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = process.cwd();
const INPUT_DIR = path.join(ROOT, 'assets', 'stickers-source');
const OUTPUT_DIR = path.join(ROOT, 'assets', 'stickers');
const CATALOG_PATH = path.join(ROOT, 'src', 'data', 'stickerImageCatalog.ts');

const VALID_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const KEY_PATTERN = /^[A-Z]{3}-\d+$/;

async function ensureDir(dirPath) {
  await fs.mkdir(dirPath, { recursive: true });
}

function getKeyFromFile(fileName) {
  const ext = path.extname(fileName).toLowerCase();
  const base = path.basename(fileName, ext).toUpperCase();
  if (!VALID_EXTENSIONS.has(ext)) return null;
  if (!KEY_PATTERN.test(base)) return null;
  return { key: base, ext };
}

async function build() {
  await ensureDir(INPUT_DIR);
  await ensureDir(OUTPUT_DIR);

  const files = await fs.readdir(INPUT_DIR);
  const stickerFiles = files
    .map((fileName) => ({ fileName, parsed: getKeyFromFile(fileName) }))
    .filter((item) => item.parsed !== null)
    .sort((a, b) => a.parsed.key.localeCompare(b.parsed.key));

  if (stickerFiles.length === 0) {
    console.log('No sticker files found in assets/stickers-source.');
    console.log('Use naming format TEAMCODE-number, e.g. BRA-1.jpg, ARG-10.png');
    return;
  }

  const requireLines = [];

  for (const item of stickerFiles) {
    const { key } = item.parsed;
    const inputPath = path.join(INPUT_DIR, item.fileName);
    const outputFileName = `${key}.webp`;
    const outputPath = path.join(OUTPUT_DIR, outputFileName);

    // Balanced preset: good visual quality with low app size.
    await sharp(inputPath)
      .resize({ width: 360, height: 520, fit: 'cover' })
      .webp({ quality: 72, effort: 4 })
      .toFile(outputPath);

    requireLines.push(`  '${key}': require('../../assets/stickers/${outputFileName}'),`);
  }

  const catalogContent = `export type StickerImageCatalog = Record<string, number>;

// Auto-generated by scripts/build-sticker-catalog.mjs
export const STICKER_IMAGE_CATALOG: StickerImageCatalog = {
${requireLines.join('\n')}
};
`;

  await fs.writeFile(CATALOG_PATH, catalogContent, 'utf8');

  console.log(`Processed ${stickerFiles.length} stickers.`);
  console.log(`Generated ${path.relative(ROOT, CATALOG_PATH)}.`);
}

build().catch((error) => {
  console.error(error);
  process.exit(1);
});
